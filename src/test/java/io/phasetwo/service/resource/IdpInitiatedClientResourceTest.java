/** Tests for {@code POST /realms/{realm}/orgs/{orgId}/idps/clients} (IdP-initiated SSO client). */
@JBossLog
public class IdpInitiatedClientResourceTest extends AbstractOrganizationTest {

  private final List<String> createdOrgIds = new ArrayList<>();
  private final List<String> createdUserIds = new ArrayList<>();
  private final List<String> createdClientIds = new ArrayList<>();
  private final List<String> createdIdpAliases = new ArrayList<>();

  @AfterEach
  void cleanup() {
    for (String clientId : createdClientIds) {
      keycloak
          .realm(REALM)
          .clients()
          .findByClientId(clientId)
          .forEach(c -> keycloak.realm(REALM).clients().get(c.getId()).remove());
    }
    for (String alias : createdIdpAliases) {
      try {
        keycloak.realm(REALM).identityProviders().get(alias).remove();
      } catch (Exception e) {
        log.debugf("idp %s already gone: %s", alias, e.getMessage());
      }
    }
    for (String orgId : createdOrgIds) {
      try {
        deleteOrganization(orgId);
      } catch (Exception e) {
        log.warnf("could not clean up organization %s: %s", orgId, e.getMessage());
      }
    }
    for (String userId : createdUserIds) {
      try {
        deleteUser(keycloak, REALM, userId);
      } catch (Exception e) {
        log.warnf("could not clean up user %s: %s", userId, e.getMessage());
      }
    }
    createdClientIds.clear();
    createdIdpAliases.clear();
    createdOrgIds.clear();
    createdUserIds.clear();
  }

  private String newOrg(String slug) throws IOException {
    OrganizationRepresentation rep =
        new OrganizationRepresentation()
            .name("idpi-" + slug)
            .domains(List.of("idpi-" + slug + ".example.com"));
    String orgId = createOrganization(rep).getId();
    createdOrgIds.add(orgId);
    return orgId;
  }

  /** The exact body the IdP wizard sends. */
  private Map<String, Object> wizardBody(String alias) {
    String clientId = "idp-initiated-" + alias;
    createdClientIds.add(clientId);
    Map<String, Object> attributes = new HashMap<>();
    attributes.put("saml_idp_initiated_sso_url_name", clientId);
    attributes.put("saml_idp_initiated_sso_relay_state", "");
    attributes.put("saml.force.post.binding", "true");
    attributes.put("saml_assertion_consumer_url_redirect", "");
    attributes.put("saml_assertion_consumer_url_post", "https://app.example.com/acs");
    attributes.put("phasetwo.idp-initiated.alias", alias);
    Map<String, Object> body = new HashMap<>();
    body.put("protocol", "saml");
    body.put("clientId", clientId);
    body.put("name", "");
    body.put("description", "Generated by the IdP wizard for identity provider " + alias);
    body.put("attributes", attributes);
    return body;
  }

  @SuppressWarnings("unchecked")
  private Map<String, Object> attrs(Map<String, Object> body) {
    return (Map<String, Object>) body.get("attributes");
  }

  private ClientRepresentation findClient(String clientId) {
    List<ClientRepresentation> found = keycloak.realm(REALM).clients().findByClientId(clientId);
    return found.isEmpty() ? null : found.get(0);
  }

  private Keycloak orgMember(String orgId, String username, String... roles) throws IOException {
    UserRepresentation user = createUserWithCredentials(keycloak, REALM, username, "pass");
    createdUserIds.add(user.getId());
    putRequest("foo", orgId, "members", user.getId());
    for (String role : roles) {
      grantUserRole(orgId, role, user.getId());
    }
    return getKeycloak(REALM, ADMIN_CLI, username, "pass");
  }

  @Test
  void createsClientFromWizardBody() throws IOException {
    String orgId = newOrg("ok");
    var resp = postRequest(wizardBody("acme-ok"), orgId, "idps", "clients");
    assertThat(resp.getStatusCode(), is(Status.CREATED.getStatusCode()));

    ClientRepresentation client = findClient("idp-initiated-acme-ok");
    assertThat(client, notNullValue());
    assertThat(resp.getHeader("Location"), endsWith("/idps/clients/" + client.getId()));

    assertThat(client.getProtocol(), is("saml"));
    assertThat(client.getAttributes(), hasEntry("phasetwo.idp-initiated.org-id", orgId));
    assertThat(client.getAttributes(), hasEntry("phasetwo.idp-initiated.alias", "acme-ok"));
    assertThat(
        client.getAttributes(),
        hasEntry("saml_idp_initiated_sso_url_name", "idp-initiated-acme-ok"));
    assertThat(
        client.getAttributes(),
        hasEntry("saml_assertion_consumer_url_post", "https://app.example.com/acs"));
    assertThat(client.getAttributes(), hasEntry("saml.force.post.binding", "true"));
    assertThat(client.isServiceAccountsEnabled(), is(false));
    assertThat(client.isDirectAccessGrantsEnabled(), is(false));
    assertThat(client.isImplicitFlowEnabled(), is(false));
    assertThat(client.isPublicClient(), is(false));
    assertThat(client.getRedirectUris(), anyOf(nullValue(), empty()));
    assertThat(client.getAdminUrl(), anyOf(nullValue(), is("")));
    assertThat(client.getAuthenticationFlowBindingOverrides(), anyOf(nullValue(), is(Map.of())));
  }

  @Test
  void orgIdpManagerCanCreateClient() throws IOException {
    String orgId = newOrg("mgr");
    Keycloak manager =
        orgMember(
            orgId,
            "idpi-manager",
            OrganizationAdminAuth.ORG_ROLE_VIEW_IDENTITY_PROVIDERS,
            OrganizationAdminAuth.ORG_ROLE_MANAGE_IDENTITY_PROVIDERS);
    var resp = postRequest(manager, wizardBody("acme-mgr"), "%s/idps/clients".formatted(orgId));
    assertThat(resp.getStatusCode(), is(Status.CREATED.getStatusCode()));
    assertThat(
        findClient("idp-initiated-acme-mgr").getAttributes(),
        hasEntry("phasetwo.idp-initiated.org-id", orgId));
  }

  @Test
  void duplicateClientIdIsConflict() throws IOException {
    String orgId = newOrg("dup");
    var first = postRequest(wizardBody("acme-dup"), orgId, "idps", "clients");
    assertThat(first.getStatusCode(), is(Status.CREATED.getStatusCode()));
    var second = postRequest(wizardBody("acme-dup"), orgId, "idps", "clients");
    assertThat(second.getStatusCode(), is(Status.CONFLICT.getStatusCode()));
  }

  @Test
  void callerWithoutManageIdentityProvidersIsUnauthorized() throws IOException {
    String orgId = newOrg("noauth");
    // view-identity-providers reaches the idps sub-resource, but creating needs manage
    Keycloak viewer =
        orgMember(orgId, "idpi-viewer", OrganizationAdminAuth.ORG_ROLE_VIEW_IDENTITY_PROVIDERS);
    var resp = postRequest(viewer, wizardBody("acme-viewer"), "%s/idps/clients".formatted(orgId));
    assertThat(resp.getStatusCode(), is(Status.UNAUTHORIZED.getStatusCode()));

    // a member with no org roles cannot reach the idps sub-resource at all
    Keycloak member = orgMember(orgId, "idpi-member");
    resp = postRequest(member, wizardBody("acme-viewer"), "%s/idps/clients".formatted(orgId));
    assertThat(resp.getStatusCode(), is(Status.UNAUTHORIZED.getStatusCode()));

    assertThat(findClient("idp-initiated-acme-viewer"), nullValue());
  }

  private void assertRejected(String orgId, String alias, Consumer<Map<String, Object>> mutate)
      throws IOException {
    Map<String, Object> body = wizardBody(alias);
    mutate.accept(body);
    var resp = postRequest(body, orgId, "idps", "clients");
    assertThat(resp.getStatusCode(), is(Status.BAD_REQUEST.getStatusCode()));
    assertThat(findClient("idp-initiated-" + alias), nullValue());
  }

  @Test
  void rejectsOtherClientShapes() throws IOException {
    String orgId = newOrg("shape");
    String alias = "acme-shape";

    assertRejected(orgId, alias, b -> b.put("protocol", "openid-connect"));
    assertRejected(orgId, alias, b -> b.remove("protocol"));
    assertRejected(
        orgId,
        alias,
        b -> {
          b.put("clientId", "acme-shape");
          attrs(b).put("saml_idp_initiated_sso_url_name", "acme-shape");
        });
    assertRejected(orgId, alias, b -> attrs(b).put("saml_idp_initiated_sso_url_name", "other"));
    assertRejected(orgId, alias, b -> attrs(b).put("phasetwo.idp-initiated.alias", "other"));
    assertRejected(orgId, alias, b -> attrs(b).remove("phasetwo.idp-initiated.alias"));
    assertRejected(orgId, alias, b -> attrs(b).put("phasetwo.idp-initiated.org-id", "spoofed"));
    assertRejected(orgId, alias, b -> attrs(b).put("saml.signature.algorithm", "RSA_SHA1"));
    assertRejected(orgId, alias, b -> attrs(b).put("saml.force.post.binding", "maybe"));
    assertRejected(
        orgId, alias, b -> attrs(b).put("saml_assertion_consumer_url_post", "javascript:alert(1)"));
    assertRejected(orgId, alias, b -> b.put("redirectUris", List.of("*")));
    assertRejected(orgId, alias, b -> b.put("serviceAccountsEnabled", true));
    assertRejected(orgId, alias, b -> b.put("directAccessGrantsEnabled", true));
    assertRejected(orgId, alias, b -> b.put("adminUrl", "https://evil.example.com"));
    assertRejected(
        orgId,
        alias,
        b -> b.put("authenticationFlowBindingOverrides", Map.of("browser", "some-flow-id")));
    assertRejected(
        orgId,
        alias,
        b ->
            b.put(
                "protocolMappers",
                List.of(Map.of("name", "m", "protocol", "saml", "protocolMapper", "x"))));
    assertRejected(orgId, alias, b -> b.put("defaultClientScopes", List.of("roles")));
    assertRejected(orgId, alias, b -> b.put("id", "chosen-id"));
  }

  @Test
  void rejectsAliasOfAnotherOrganizationsIdp() throws IOException {
    String ownerOrg = newOrg("owner");
    String otherOrg = newOrg("other");

    String alias = "acme-owned";
    IdentityProviderRepresentation idp = new IdentityProviderRepresentation();
    idp.setAlias(alias);
    idp.setProviderId("saml");
    idp.setEnabled(true);
    idp.setConfig(
        new ImmutableMap.Builder<String, String>()
            .put("singleSignOnServiceUrl", "https://idp.example.com/sso")
            .put("entityId", "https://idp.example.com")
            .build());
    var created = postRequest(idp, ownerOrg, "idps");
    assertThat(created.getStatusCode(), is(Status.CREATED.getStatusCode()));
    createdIdpAliases.add(alias);

    var resp = postRequest(wizardBody(alias), otherOrg, "idps", "clients");
    assertThat(resp.getStatusCode(), is(Status.BAD_REQUEST.getStatusCode()));
    assertThat(findClient("idp-initiated-" + alias), nullValue());

    // the owning organization can create it
    resp = postRequest(wizardBody(alias), ownerOrg, "idps", "clients");
    assertThat(resp.getStatusCode(), is(Status.CREATED.getStatusCode()));
    assertThat(findClient("idp-initiated-" + alias), not(nullValue()));
  }
}
