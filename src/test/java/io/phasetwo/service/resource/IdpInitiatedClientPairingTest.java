package io.phasetwo.service.resource;

import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.is;
import static org.hamcrest.Matchers.notNullValue;
import static org.hamcrest.Matchers.nullValue;

import com.google.common.collect.ImmutableMap;
import io.phasetwo.client.openapi.model.OrganizationRepresentation;
import io.phasetwo.service.AbstractOrganizationTest;
import jakarta.ws.rs.NotFoundException;
import jakarta.ws.rs.core.Response;
import jakarta.ws.rs.core.Response.Status;
import java.io.IOException;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import lombok.extern.jbosslog.JBossLog;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.keycloak.admin.client.resource.RealmResource;
import org.keycloak.representations.idm.ClientRepresentation;
import org.keycloak.representations.idm.IdentityProviderRepresentation;

/** Removing an identity provider removes its IdP-initiated SAML client, and vice versa. */
@JBossLog
public class IdpInitiatedClientPairingTest extends AbstractOrganizationTest {

  private final List<String> createdOrgIds = new ArrayList<>();
  private final List<String> createdClientIds = new ArrayList<>();
  private final List<String> createdIdpAliases = new ArrayList<>();

  @AfterEach
  void cleanup() {
    RealmResource realm = keycloak.realm(REALM);
    for (String clientId : createdClientIds) {
      realm
          .clients()
          .findByClientId(clientId)
          .forEach(c -> realm.clients().get(c.getId()).remove());
    }
    for (String alias : createdIdpAliases) {
      try {
        realm.identityProviders().get(alias).remove();
      } catch (NotFoundException e) {
        // already removed
      }
    }
    for (String orgId : createdOrgIds) {
      try {
        deleteOrganization(orgId);
      } catch (Exception e) {
        log.warnf("could not clean up organization %s: %s", orgId, e.getMessage());
      }
    }
    createdClientIds.clear();
    createdIdpAliases.clear();
    createdOrgIds.clear();
  }

  private RealmResource realm() {
    return keycloak.realm(REALM);
  }

  private String newOrg(String slug) throws IOException {
    OrganizationRepresentation rep =
        new OrganizationRepresentation()
            .name("idpi-pair-" + slug)
            .domains(List.of("idpi-pair-" + slug + ".example.com"));
    String orgId = createOrganization(rep).getId();
    createdOrgIds.add(orgId);
    return orgId;
  }

  private IdentityProviderRepresentation samlIdp(String alias) {
    createdIdpAliases.add(alias);
    IdentityProviderRepresentation idp = new IdentityProviderRepresentation();
    idp.setAlias(alias);
    idp.setProviderId("saml");
    idp.setEnabled(true);
    idp.setConfig(
        new HashMap<>(
            new ImmutableMap.Builder<String, String>()
                .put("singleSignOnServiceUrl", "https://idp.example.com/sso")
                .put("entityId", "https://idp.example.com")
                .build()));
    return idp;
  }

  private void createRealmIdp(RealmResource realm, String alias) {
    try (Response resp = realm.identityProviders().create(samlIdp(alias))) {
      assertThat(resp.getStatus(), is(Status.CREATED.getStatusCode()));
    }
  }

  /** The client body the IdP wizard sends. */
  private Map<String, Object> wizardClient(String alias) {
    String clientId = "idp-initiated-" + alias;
    createdClientIds.add(clientId);
    Map<String, Object> attributes = new HashMap<>();
    attributes.put("saml_idp_initiated_sso_url_name", clientId);
    attributes.put("saml_idp_initiated_sso_relay_state", "");
    attributes.put("saml.force.post.binding", "false");
    attributes.put("saml_assertion_consumer_url_redirect", "https://app.example.com/acs");
    attributes.put("saml_assertion_consumer_url_post", "");
    attributes.put("phasetwo.idp-initiated.alias", alias);
    Map<String, Object> body = new HashMap<>();
    body.put("protocol", "saml");
    body.put("clientId", clientId);
    body.put("name", "");
    body.put("description", "Generated by the IdP wizard for identity provider " + alias);
    body.put("attributes", attributes);
    return body;
  }

  private ClientRepresentation clientRep(String clientId, Map<String, String> attributes) {
    createdClientIds.add(clientId);
    ClientRepresentation client = new ClientRepresentation();
    client.setClientId(clientId);
    client.setProtocol("saml");
    client.setAttributes(new HashMap<>(attributes));
    return client;
  }

  private void createRealmClient(RealmResource realm, ClientRepresentation client) {
    try (Response resp = realm.clients().create(client)) {
      assertThat(resp.getStatus(), is(Status.CREATED.getStatusCode()));
    }
  }

  private void createWizardClientRealmWide(RealmResource realm, String alias) {
    Map<String, Object> body = wizardClient(alias);
    @SuppressWarnings("unchecked")
    Map<String, String> attributes = (Map<String, String>) body.get("attributes");
    createRealmClient(realm, clientRep((String) body.get("clientId"), attributes));
  }

  private ClientRepresentation findClient(RealmResource realm, String clientId) {
    List<ClientRepresentation> found = realm.clients().findByClientId(clientId);
    return found.isEmpty() ? null : found.get(0);
  }

  private IdentityProviderRepresentation findIdp(RealmResource realm, String alias) {
    try {
      return realm.identityProviders().get(alias).toRepresentation();
    } catch (NotFoundException e) {
      return null;
    }
  }

  private void deleteClientByClientId(RealmResource realm, String clientId) {
    realm.clients().get(findClient(realm, clientId).getId()).remove();
  }

  @Test
  void removingRealmIdpRemovesPairedClient() {
    createRealmIdp(realm(), "pair-realm-a");
    createWizardClientRealmWide(realm(), "pair-realm-a");

    realm().identityProviders().get("pair-realm-a").remove();

    assertThat(findClient(realm(), "idp-initiated-pair-realm-a"), nullValue());
  }

  @Test
  void removingPairedClientRemovesIdp() {
    createRealmIdp(realm(), "pair-realm-b");
    createWizardClientRealmWide(realm(), "pair-realm-b");

    deleteClientByClientId(realm(), "idp-initiated-pair-realm-b");

    assertThat(findIdp(realm(), "pair-realm-b"), nullValue());
  }

  @Test
  void removingOrgIdpThroughOrgsApiRemovesPairedClient() throws IOException {
    String orgId = newOrg("delete");
    var client = postRequest(wizardClient("pair-org-a"), orgId, "idps", "clients");
    assertThat(client.getStatusCode(), is(Status.CREATED.getStatusCode()));
    var idp = postRequest(samlIdp("pair-org-a"), orgId, "idps");
    assertThat(idp.getStatusCode(), is(Status.CREATED.getStatusCode()));

    var deleted = deleteRequest(orgId, "idps", "pair-org-a");
    assertThat(deleted.getStatusCode(), is(Status.NO_CONTENT.getStatusCode()));

    assertThat(findIdp(realm(), "pair-org-a"), nullValue());
    assertThat(findClient(realm(), "idp-initiated-pair-org-a"), nullValue());
  }

  @Test
  void removingOrgPairedClientRemovesOrgIdp() throws IOException {
    String orgId = newOrg("client");
    postRequest(wizardClient("pair-org-b"), orgId, "idps", "clients");
    postRequest(samlIdp("pair-org-b"), orgId, "idps");

    deleteClientByClientId(realm(), "idp-initiated-pair-org-b");

    assertThat(findIdp(realm(), "pair-org-b"), nullValue());
  }

  @Test
  void unlinkingOrgIdpKeepsClient() throws IOException {
    String orgId = newOrg("unlink");
    postRequest(wizardClient("pair-org-c"), orgId, "idps", "clients");
    postRequest(samlIdp("pair-org-c"), orgId, "idps");

    var unlinked = postRequest("", orgId, "idps", "pair-org-c", "unlink");
    assertThat(unlinked.getStatusCode(), is(Status.NO_CONTENT.getStatusCode()));

    assertThat(findIdp(realm(), "pair-org-c"), notNullValue());
    assertThat(findClient(realm(), "idp-initiated-pair-org-c"), notNullValue());
  }

  @Test
  void pairOwnedByAnotherOrganizationIsUntouched() throws IOException {
    String ownerOrg = newOrg("owner");
    String otherOrg = newOrg("other");
    postRequest(samlIdp("pair-org-d"), ownerOrg, "idps");
    // a client recorded for a different organization than the one owning the identity provider
    createRealmClient(
        realm(),
        clientRep(
            "idp-initiated-pair-org-d",
            Map.of(
                "saml_idp_initiated_sso_url_name", "idp-initiated-pair-org-d",
                "phasetwo.idp-initiated.alias", "pair-org-d",
                "phasetwo.idp-initiated.org-id", otherOrg)));

    deleteClientByClientId(realm(), "idp-initiated-pair-org-d");
    assertThat(findIdp(realm(), "pair-org-d"), notNullValue());

    createRealmClient(
        realm(),
        clientRep(
            "idp-initiated-pair-org-d",
            Map.of(
                "saml_idp_initiated_sso_url_name", "idp-initiated-pair-org-d",
                "phasetwo.idp-initiated.alias", "pair-org-d",
                "phasetwo.idp-initiated.org-id", otherOrg)));
    realm().identityProviders().get("pair-org-d").remove();
    assertThat(findClient(realm(), "idp-initiated-pair-org-d"), notNullValue());
  }

  @Test
  void namingConventionPairsOnlyIdpInitiatedSamlClients() {
    // convention match without the alias attribute: SAML, prefix, and an IdP-initiated URL name
    createRealmIdp(realm(), "pair-conv-a");
    createRealmClient(
        realm(),
        clientRep(
            "idp-initiated-pair-conv-a",
            Map.of("saml_idp_initiated_sso_url_name", "idp-initiated-pair-conv-a")));
    realm().identityProviders().get("pair-conv-a").remove();
    assertThat(findClient(realm(), "idp-initiated-pair-conv-a"), nullValue());

    // same name, but no IdP-initiated URL name: not a pair
    createRealmIdp(realm(), "pair-conv-b");
    createRealmClient(realm(), clientRep("idp-initiated-pair-conv-b", Map.of()));
    realm().identityProviders().get("pair-conv-b").remove();
    assertThat(findClient(realm(), "idp-initiated-pair-conv-b"), notNullValue());

    createRealmIdp(realm(), "pair-conv-c");
    deleteClientByClientId(realm(), "idp-initiated-pair-conv-b");
    assertThat(findIdp(realm(), "pair-conv-c"), notNullValue());
  }

  @Test
  void unrelatedClientsAndIdpsAreUntouched() {
    createRealmIdp(realm(), "pair-unrelated");
    createRealmClient(realm(), clientRep("pair-unrelated", Map.of()));
    createRealmIdp(realm(), "pair-unrelated-2");
    createWizardClientRealmWide(realm(), "pair-unrelated-2");

    deleteClientByClientId(realm(), "pair-unrelated");
    assertThat(findIdp(realm(), "pair-unrelated"), notNullValue());

    realm().identityProviders().get("pair-unrelated").remove();
    assertThat(findClient(realm(), "idp-initiated-pair-unrelated-2"), notNullValue());
    assertThat(findIdp(realm(), "pair-unrelated-2"), notNullValue());
  }

  @Test
  void counterpartAlreadyGoneIsNotAnError() {
    // client whose identity provider never existed
    createWizardClientRealmWide(realm(), "pair-gone-a");
    deleteClientByClientId(realm(), "idp-initiated-pair-gone-a");
    assertThat(findClient(realm(), "idp-initiated-pair-gone-a"), nullValue());

    // identity provider whose client never existed
    createRealmIdp(realm(), "pair-gone-b");
    realm().identityProviders().get("pair-gone-b").remove();
    assertThat(findIdp(realm(), "pair-gone-b"), nullValue());
  }
}
